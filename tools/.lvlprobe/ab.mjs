import { chromium } from 'playwright';
const a = Object.fromEntries(process.argv.slice(2).reduce((acc,c,i,arr)=>{if(c.startsWith('--'))acc.push([c.slice(2),arr[i+1]]);return acc;},[]));
const PORT = a.port ?? 5312;
const browser = await chromium.launch({ args: ['--use-angle=metal','--ignore-gpu-blocklist','--use-gl=angle','--disable-frame-rate-limit'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
const errs=[]; page.on('pageerror',e=>errs.push(e.message));
await page.goto(`http://127.0.0.1:${PORT}/`, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__READY__ === true, { timeout: 40000 });
await new Promise(r=>setTimeout(r,2000));
await page.evaluate(p=>window.__POSE__?.(p), a.pose);
await new Promise(r=>setTimeout(r,600));
await page.evaluate(a.setup);
await page.evaluate(()=>{for(const id of ['enter','boot']){const el=document.getElementById(id); if(el)el.style.display='none';}});
await new Promise(r=>setTimeout(r,2000));
await page.screenshot({ path: a.out + '.a.png', type:'png' });
await page.evaluate(()=>{ window.__TESTOBJ__.castShadow = false; });
await new Promise(r=>setTimeout(r,2000));
await page.screenshot({ path: a.out + '.b.png', type:'png' });
console.log('OK', errs.slice(0,5));
await browser.close();
